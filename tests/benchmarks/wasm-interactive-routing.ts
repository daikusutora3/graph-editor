import { readFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

import { RUST_KERNEL_URL } from "../../features/graph-editor/compute/kernel-asset";
import {
  initializeRustKernelFromBytes,
  withRustKernelSuppressed,
} from "../../features/graph-editor/compute/rust-kernel";
import { createEmptyGraphModel } from "../../features/graph-editor/core/graph/graph-factory";
import type { GraphModel } from "../../features/graph-editor/core/graph/model";
import {
  createEdgeRoutingTask,
  resolveRoutingMode,
} from "../../features/graph-editor/core/layout/edge-routing";
import { interactiveRerouteEdgeIdsTask } from "../../features/graph-editor/core/layout/interactive-routing";

// Run alone. Seven 10-run CPU batches after ten warmups include packing/copying,
// batching, IDs and yields; batching avoids overreading microsecond noise.
// they exclude Worker messaging, loading and painting. Metadata is generated by
// the real complete routing task, rather than assuming all routes are straight.
await initializeRustKernelFromBytes(readFileSync(`public${RUST_KERNEL_URL}`));
const baselineRoot = argument("--baseline-root");
const originalTask = baselineRoot
  ? (
      (await import(
        pathToFileURL(
          join(
            baselineRoot,
            "features/graph-editor/core/layout/interactive-routing.ts",
          ),
        ).href
      )) as {
        interactiveRerouteEdgeIdsTask: typeof interactiveRerouteEdgeIdsTask;
      }
    ).interactiveRerouteEdgeIdsTask
  : null;

for (const edgeCount of [64, 400, 5000]) {
  const graph = fixture(edgeCount);
  const routes = complete(createEdgeRoutingTask(graph, { mode: "quality" }));
  for (const near of [false, true]) {
    const movedGraph = near
      ? {
          ...graph,
          nodes: graph.nodes.map((node, i) =>
            i < 500 ? node : { ...node, x: node.x - 10000, y: node.y + 40 },
          ),
        }
      : graph;
    for (const movedCount of [1, 127, 128, 500, 1000]) {
      const moved = new Set(
        (movedCount === 1000
          ? graph.nodes
          : graph.nodes.slice(500, 500 + movedCount)
        ).map((node) => node.id),
      );
      const run = () =>
        complete(interactiveRerouteEdgeIdsTask(movedGraph, routes, moved));
      const javascript = measure(() => withRustKernelSuppressed(run));
      const rust = measure(run);
      const original = originalTask
        ? measure(() =>
            withRustKernelSuppressed(() =>
              complete(originalTask(movedGraph, routes, moved)),
            ),
          )
        : null;
      const sameOutput = javascript.ids === rust.ids;
      console.log(
        JSON.stringify({
          name: `interactive ${near ? "near" : "far"} ${edgeCount} edges, ${movedCount} moved`,
          nodes: graph.nodes.length,
          mode: resolveRoutingMode(graph, "quality"),
          readyRoutes: [...routes.values()].filter(
            (route) => route.status === "ready" || route.status === undefined,
          ).length,
          straightRoutes: [...routes.values()].filter(
            (route) =>
              route.bowPx === 0 && route.controlPointWeights.length <= 1,
          ).length,
          javascriptMedianMs: javascript.medianMs,
          rustMedianMs: rust.medianMs,
          speedup: javascript.medianMs / rust.medianMs,
          sameOutput,
          ...(original
            ? {
                originalMedianMs: original.medianMs,
                overallSpeedup: original.medianMs / rust.medianMs,
                sameOriginalOutput: original.ids === rust.ids,
              }
            : {}),
        }),
      );
      if (!sameOutput) process.exitCode = 1;
      if (original && original.ids !== rust.ids) process.exitCode = 1;
    }
  }
}

function argument(flag: string) {
  const index = process.argv.indexOf(flag);
  return index < 0 ? undefined : process.argv[index + 1];
}

function measure(run: () => Set<string> | null) {
  for (let i = 0; i < 10; i++) run();
  const times: number[] = [];
  let result: Set<string> | null = null;
  for (let i = 0; i < 7; i++) {
    const start = performance.now();
    for (let repeat = 0; repeat < 10; repeat++) result = run();
    times.push((performance.now() - start) / 10);
  }
  return {
    medianMs: times.toSorted((a, b) => a - b)[3]!,
    ids: JSON.stringify(result ? [...result] : null),
  };
}

function complete<T>(task: Generator<void, T>): T {
  let step = task.next();
  while (!step.done) step = task.next();
  return step.value;
}

function fixture(edgeCount: number): GraphModel {
  const gridEdges = Array.from({ length: 500 }, (_, i) => [
    ...(i % 25 < 24
      ? [{ id: `h${i}`, source: `n${i}`, target: `n${i + 1}` }]
      : []),
    ...(i < 475
      ? [{ id: `v${i}`, source: `n${i}`, target: `n${i + 25}` }]
      : []),
  ]).flat();
  const manyEdges = Array.from({ length: 5000 }, (_, i) => ({
    id: `e${i}`,
    source: `n${i % 500}`,
    target: `n${((i % 500) + 1 + Math.floor(i / 500)) % 500}`,
  }));
  return {
    ...createEmptyGraphModel({ autoEdgeRouting: true }),
    nodes: Array.from({ length: 1000 }, (_, i) => ({
      id: `n${i}`,
      order: i,
      label: String(i),
      x: (i % 25) * 120 + (i < 500 ? 0 : 10000),
      y: Math.floor((i % 500) / 25) * 120,
    })),
    edges:
      edgeCount <= gridEdges.length ? gridEdges.slice(0, edgeCount) : manyEdges,
  };
}
